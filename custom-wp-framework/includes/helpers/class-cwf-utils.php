// Load required classes.
use Custom_WP_Framework\Includes\CWF_Config;

/**
 * General plugin functions and utilities.
 * 
 * @since   1.0.0
 * @param   void
 * @return  void
 */
class CWF_Utils {

    /**
     * Function to log to a rolling text file.
     * 
     * @since   1.0.0
     * @param   string      $text
     * @return  void
     */
    public static function log_to_file( $text ){

        /**
         * Output directory for log files.
         * 
         * @since   1.0.0
         * @var     string  $output_dir
         */
        $output_dir = CUSTOM_WP_FRAMEWORK_FOLDER . 'logs/';
        
        /**
         * Write supplied text to file.
         */
        file_put_contents( $output_dir . "log_" . date('Y-m-d') . ".txt", date('Y-m-d H:i:s: ') . $text . "\r\n", FILE_APPEND );
    }

    /**
     * Function to log exception details.
     * 
     * @since   1.0.0
     * @param   Exception   $e
     * @return  void
     */
    public static function log_exception( $e ) {

        /**
         * Log Exception error message to file.
         */
        self::log_to_file( $e->getMessage() );

        /**
         * Log stack trace to file.
         */
        self::log_to_file( 'Stack trace: ' . $e->getTraceAsString() );

    }

    /**
     * Function to stop execution and display error message.
     * 
     * @since   1.0.0
     * @param   Exception   $e
     * @return  void
     */
    public static function display_exception( $e ) {

        /**
         * Kill execution and display error message.
         */
        wp_die( __( sprintf( 'Error occurred: %s. Please try again later or contact support if issue persists.', $e->getCode() ), CUSTOM_WP_FRAMEWORK_TEXT_DOMAIN ) );

    }

    /**
     * Function to identify whether current admin screen is generated by plugin.
     * 
     * @since   1.0.0
     * @param   void
     * @return  bool
     */
    public static function is_cwf_admin() {

        if( is_admin() ) {

            /**
             * Get current admin page.
             */
            $screen = get_current_screen();
            /**
             * Retrieve all screen names for admin pages.
             */
            $cwf_admin_areas = CWF_Config::get_setting_value( 'admin_screens' );

            foreach( $cwf_admin_areas as $cwf_admin_area ) {
                foreach( $cwf_admin_area as $cwf_admin_page ) {
                    if( $screen->base === $cwf_admin_page ) {
                        return true;
                    }
                }
            }
        }

        return false;
    }
}