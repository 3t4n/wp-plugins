<?php 

namespace Custom_WP_Framework\Includes\Core\Components;

// Exit if accessed directly.
if ( ! defined ( 'ABSPATH' ) ) { 
	exit(); 
} 

// Load required classes.
use Custom_WP_Framework\Admin\Models;

/**
 * Functions to run on init() hook. 
 * 
 * Register all custom entities and flush rewrite rules if applicable.
 *
 * @since   1.0.0
 */
class CWF_Init {   
    
    /**
     * Register all custom post types saved by plugin.
     * 
     * @since   1.0.0
     * @param   void
     * @return  void
     */
    public function cwf_register_custom_post_types(){
        
        /**
         * Create new instance of CPT data model.
         * 
         * @since   1.0.0
         * @var     $model_cpt
         */
        $model_cpt = new Models\Custom_Post_Types\CWF_CPT_DataModel();

        /**
         * Get all active custom post types to be registered by plugin.
         */
        $model_cpt->get_all_cwf_custom_post_types( true );

        if( ! empty ( $model_cpt->results ) ) {
            
            /**
             * Format custom post type data for registration.
             */
            $model_cpt->registration_format();

            /**
             * Action hook before custom post type registration.
             * 
             * @since   1.0.0
             * @param   array   $model_cpt->cpt_collection  Array of custom post types to register.
             */
            do_action( 'cwf_before_cpt_registration', $model_cpt->cpt_collection );

            if ( ! empty ( $model_cpt->cpt_collection ) ) {

                if( is_array ( $model_cpt->cpt_collection ) ) {

                    /**
                     * Iterate through each custom post type to be registered.
                     */
                    foreach( $model_cpt->cpt_collection as $cpt ) {

                         /**
                         * Register the custom post type.
                         */
                        register_post_type( $cpt['cpt_key'], $cpt['cpt_args'] );

                        /**
                         * Add link to edit cpt admin page above the posts table.
                         */
                        add_filter( "views_edit-{$cpt['cpt_key']}", array( &$this, 'add_cwf_cpt_link' ) );
                        
                    }
                }
            }

            /**
             * Action hook after custom post type registration.
             * 
             * @since   1.0.0
             * @param   array   $model_cpt->cpt_collection  Array of custom post types that were registered.
             */
            do_action( 'cwf_after_cpt_registration', $model_cpt->cpt_collection );
        }
    }

    /**
     * Flush rewrite rules if required.
     * 
     * @since   1.0.0
     * @param   void
     * @return  void
     */
    public function cwf_flush_rewrite_rules(){
    
        if ( get_option( 'cwf_rewrite_required' ) == 1 ) {

            /**
             * Flush rewrite rules.
             */
            flush_rewrite_rules();
            
            /**
             * Update rewrite required flag to 0 as rewrite rules have been flushed.
             */
            update_option( 'cwf_rewrite_required', 0 );
        }
    }

    /**
     * Add link to edit admin page above posts table.
     * 
     * @since   1.0.0
     * @param   array   $views  Collection of WP_List_Table views for posts table.
     * @return  array   $views  Collection of WP_List_Table views for posts table.
     */
    function add_cwf_cpt_link ( $views ) {


        /**
        * Create new instance of CPT data model.
        * 
        * @since   1.0.0
        * @var     $model_cpt
        */
       $model_cpt = new Models\Custom_Post_Types\CWF_CPT_DataModel();

       /**
        * Get all custom post types to be registered by plugin.
        */
       $model_cpt->get_all_cwf_custom_post_types();

       /**
        * Cycle through available custom post types. 
        */
       foreach( $model_cpt->results as $cpt ) {

			$screen = get_current_screen();

            /**
             * If current cpt is equal to cpt generated by plugin, add link.
             */
           if( $screen->post_type == $cpt->cpt_key ) {

                /**
                 * Construct link to edit admin page.
                 */
                $edit_cpt_url = admin_url() . '?page=custom-wp-framework-admin-cpt-edit&id=' . $cpt->id;
               
                /**
                 * Add link to WP_List_Table views for post type.
                 */
                $views['cwf_edit_cpt_link'] = sprintf( '<a href="' . $edit_cpt_url . '">%s</a>', __( 'Edit with Custom WP Framework', CUSTOM_WP_FRAMEWORK_TEXT_DOMAIN ) );

           }

       }

       return $views;
       
   }
}