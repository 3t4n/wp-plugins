/**
 * Handling the form submission of registration form generated by shortcode
 * 
 * @since 1.0.0
 * @author Niraj Gohel
 */
add_action('admin_post_nopriv_spec_frntlr_register',function(){
	if(isset($_POST['username'])){
		if(sanitize_text_field($_POST['password'])==sanitize_text_field($_POST['confirm_password'])){
			$cred=array();
			$cred['user_login']=sanitize_user($_POST['username']);
			$cred['user_pass']=sanitize_text_field($_POST['password']);
			$cred['user_email']=sanitize_email($_POST['email']);
			$cred['first_name']=sanitize_text_field($_POST['fname']);
			$cred['last_name']=sanitize_text_field($_POST['lname']);
			$user_id=wp_insert_user($cred);
			if(!is_wp_error($user_id)){
				wp_set_auth_cookie( $user_id, true, false );
				do_action( 'wp_login', $user_login );
				wp_set_current_user($user_id);
			}
			else{
				update_option('frntlr_error',$user_id->get_error_message());	
			}
		}
		else{
			update_option('frntlr_error',__('Passwords are not matching'));
		}
	}
	wp_redirect(wp_get_referer());
});
