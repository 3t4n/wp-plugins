		</div>
		<div class="'.esc_attr('form-group').'">
		<label for="'.esc_attr('password').'">'.__('Password','spec-frntlr').' :</label>
		<input type="'.esc_attr('password').'" class="'.esc_attr('form-control').'" id="'.esc_attr('password').'" name="'.esc_attr('password').'">
		</div>
		<div class="'.esc_attr('checkbox').'">
		<label><input type="'.esc_attr('checkbox').'" name="'.esc_attr('remember').'" value="'.esc_attr('true').'">'.__(' Remember me','spec-frntlr').'</label>
		</div>
