	return esc_html($html);
});

/**
 * Handling the form submission of login form generated by shortcode
 * 
 * @since 1.0.0
 * @author Niraj Gohel
 */
add_action('admin_post_nopriv_spec_frntlr_login',function(){
	if(isset($_POST['username'])){
		$cred=array();
		$cred['user_login']=sanitize_user($_POST['username']);
		$cred['user_password']=sanitize_text_field($_POST['password']);
		if(isset($_POST['remember'])){
			$cred['remember']=true;
		}
		$user=wp_signon($cred,false);
		if(!is_wp_error($user)){
			$userID=$user->ID;
			wp_set_auth_cookie( $userID, true, false );
			do_action( 'wp_login', $user_login );
			wp_set_current_user($userID);
		}
		else{
			update_option('frntlr_error',$user->get_error_message());	
		}
	}
	wp_redirect(wp_get_referer());
});


